// viewFiles returns a small repository: a go.work with two modules, Go sources (one
// generated), a two-document YAML file, a binary file and an untracked note.
func viewFiles() map[string]string {
	return map[string]string{
		"go.work":      "go 1.27\n\nuse (\n\t./svc/a\n\t./svc/b\n)\n",
		"svc/a/go.mod": "module a\n",
		"svc/a/main.go": "package main\n\nimport \"fmt\"\n\n" +
			"// main says hi. TODO-1\nfunc main() { fmt.Println(\"hi\") }\n",
		"svc/a/main.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\n\n" +
			"package main\n",
		"svc/b/go.mod": "module b\n",
		"svc/b/b.go": "package b\n\nimport (\n\t\"os\"\n\t\"strings\"\n)\n\n" +
			"var _ = os.Args\nvar _ = strings.ToUpper\n",
		"k8s/app.yaml": "kind: Deployment\nmetadata:\n  name: api\n---\n" +
			"kind: Service\nmetadata:\n  name: api-svc\n",
		"assets/logo.png":    "\x89PNG\x00\x00binary",
		"notes/untracked.md": "TODO-2 untracked\n",
	}
}

// sourceOf returns a generated CodebaseSource mock serving viewFiles, counting each
// file's reads, with notes/untracked.md untracked.
func sourceOf(t *testing.T) (*mocks.MockCodebaseSource, map[string]int, *sync.Mutex) {
	t.Helper()
	src := mocks.NewMockCodebaseSource(gomock.NewController(t))
	files := viewFiles()
	list := make([]types.File, 0, len(files))
	for p := range files {
		list = append(list, types.File{Path: p, Untracked: p == "notes/untracked.md"})
	}
	sort.Slice(list, func(i, j int) bool { return list[i].Path < list[j].Path })
	src.EXPECT().List(gomock.Any()).Return(list, nil).AnyTimes()
	reads := map[string]int{}
	var mu sync.Mutex
	src.EXPECT().Read(gomock.Any(), gomock.Any()).DoAndReturn(
		func(_ context.Context, p string) ([]byte, error) {
			mu.Lock()
			reads[p]++
			mu.Unlock()
			body, ok := files[p]
			if !ok {
				return nil, apperr.NotFound(p)
			}
			return []byte(body), nil
		}).AnyTimes()
	return src, reads, &mu
}

// TestCodebase_FilesTextAndMatch tests the file, text and pattern views over a source.
//
// Why this test is important:
//   - Every check selects files and scans their text; the views must apply the
//     selector, skip generated and binary files, and read each file once however many
//     checks scan it.
//
// What it tests:
//   - Files applies the selector, drops the generated Go file by default and keeps it
//     on request, and TrackedOnly drops the untracked note; Match returns line and
//     column hits from text files only; repeated Text and Match calls read each file
//     once; Rendered without a renderer is CodeUnavailable.
func TestCodebase_FilesTextAndMatch(t *testing.T) {
	t.Parallel()
	src, reads, mu := sourceOf(t)
	r := codebase.New(src, codebase.NewSnapshot("t"), nil)
	ctx := t.Context()

	files, err := r.Files(ctx, types.FileSelector{Exts: []string{".go"}})
	require.NoError(t, err)
	assert.Equal(t, []string{"svc/a/main.go", "svc/b/b.go"}, paths(files))

	files, err = r.Files(
		ctx,
		types.FileSelector{Exts: []string{".go"}, IncludeGenerated: true},
	)
	require.NoError(t, err)
	assert.Equal(
		t,
		[]string{"svc/a/main.go", "svc/a/main.pb.go", "svc/b/b.go"},
		paths(files),
	)

	files, err = r.Files(
		ctx,
		types.FileSelector{Roots: []string{"notes"}, TrackedOnly: true},
	)
	require.NoError(t, err)
	assert.Empty(t, files)

	hits, err := r.Match(
		ctx,
		types.FileSelector{},
		[]*regexp.Regexp{regexp.MustCompile(`TODO-\d`)},
	)
	require.NoError(t, err)
	require.Len(t, hits, 2)
	assert.Equal(
		t,
		types.Hit{
			File:    "notes/untracked.md",
			Line:    1,
			Col:     1,
			Text:    "TODO-2 untracked",
			Pattern: `TODO-\d`,
		},
		hits[0],
	)
	assert.Equal(t, "svc/a/main.go", hits[1].File)
	assert.Equal(t, 5, hits[1].Line)

	_, err = r.Match(
		ctx,
		types.FileSelector{},
		[]*regexp.Regexp{regexp.MustCompile(`PNG`)},
	)
	require.NoError(t, err)
	text, err := r.Text(ctx, "assets/logo.png")
	require.NoError(t, err)
	assert.True(t, text.Binary)

	mu.Lock()
	for p, n := range reads {
		assert.Equal(t, 1, n, "%s read once", p)
	}
	mu.Unlock()

	_, err = r.Rendered(ctx, types.RenderSpec{ChartDir: "charts/api"})
	assert.Equal(t, apperr.CodeUnavailable, apperr.Code(err))
}

// TestCodebase_GoAndYAMLViews tests the parsed Go and YAML views.
//
// Why this test is important:
//   - Go guards and YAML checks were each parsing the whole repository on their own;
//     the views must give them module lists, ASTs and decoded documents parsed once.
//
// What it tests:
//   - Modules reads go.work; Parse returns ASTs with their imports and skips the
//     generated file; parsing the same files twice returns the same ASTs; Docs lists both
//     documents; Query selects a field with its line; Decode fills a struct.
func TestCodebase_GoAndYAMLViews(t *testing.T) {
	t.Parallel()
	src, _, _ := sourceOf(t)
	r := codebase.New(src, codebase.NewSnapshot("t"), nil)
	ctx := t.Context()

	mods, err := r.Go().Modules(ctx)
	require.NoError(t, err)
	assert.Equal(t, []string{"svc/a", "svc/b"}, mods)

	sel := types.FileSelector{Roots: []string{"svc"}}
	gofiles, err := r.Go().Parse(ctx, sel, types.ParseImports)
	require.NoError(t, err)
	require.Len(t, gofiles, 2)
	assert.Equal(t, "svc/b/b.go", gofiles[1].Path)
	assert.Len(t, gofiles[1].AST.Imports, 2)
	again, err := r.Go().Parse(ctx, sel, types.ParseImports)
	require.NoError(t, err)
	assert.Same(t, gofiles[0].AST, again[0].AST)

	docs, err := r.YAML().Docs(ctx, types.FileSelector{Exts: []string{".yaml"}})
	require.NoError(t, err)
	assert.Equal(
		t,
		[]types.YAMLDoc{
			{Path: "k8s/app.yaml", Index: 0},
			{Path: "k8s/app.yaml", Index: 1},
		},
		docs,
	)
	got, err := r.YAML().Query(ctx, docs[1], "$.metadata.name")
	require.NoError(t, err)
	assert.Equal(t, []types.YAMLMatch{{Value: "api-svc", Kind: "scalar", Line: 7}}, got)
	var obj struct {
		Kind string `yaml:"kind"`
	}
	require.NoError(t, r.YAML().Decode(ctx, docs[0], &obj))
	assert.Equal(t, "Deployment", obj.Kind)
}

// TestCodebase_RenderedIsMemoized tests that a render runs once per spec.
//
// Why this test is important:
//   - Chart renders cost seconds each; several checks assert on the same render.
//
// What it tests:
//   - Two Rendered calls for one spec call the renderer once and return its objects.
func TestCodebase_RenderedIsMemoized(t *testing.T) {
	t.Parallel()
	src, _, _ := sourceOf(t)
	renderer := mocks.NewMockRenderer(gomock.NewController(t))
	spec := types.RenderSpec{ChartDir: "charts/api", ValuesFiles: []string{"v.yaml"}}
	renderer.EXPECT().Render(gomock.Any(), spec).
		Return([]types.Object{{Kind: "Deployment", Name: "api"}}, nil).Times(1)
	r := codebase.New(src, codebase.NewSnapshot("t"), renderer)
	for range 2 {
		objs, err := r.Rendered(t.Context(), spec)
		require.NoError(t, err)
		assert.Equal(t, "api", objs[0].Name)
	}
}

// paths returns each file's path.
func paths(files []types.File) []string {
	out := make([]string, 0, len(files))
	for _, f := range files {
		out = append(out, f.Path)
	}
	return out
}

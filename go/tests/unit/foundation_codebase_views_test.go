// viewFiles returns a small repository: a go.work with two modules, Go sources (one
// generated), a two-document YAML file, a binary file and an untracked note.
func viewFiles() map[string]string {
	return map[string]string{
		textGoWork:     "go 1.27\n\nuse (\n\t./svc/a\n\t./svc/b\n)\n",
		"svc/a/go.mod": textModuleA,
		textSvcAMainGo: "package main\n\nimport \"fmt\"\n\n" +
			"// main says hi. TODO-1\nfunc main() { fmt.Println(\"hi\") }\n",
		"svc/a/main.pb.go": "// Code generated by protoc-gen-go. DO NOT EDIT.\n\n" +
			"package main\n",
		"svc/b/go.mod": textModuleB,
		textSvcBBGo: "package b\n\nimport (\n\t\"os\"\n\t\"strings\"\n)\n\n" +
			"var _ = os.Args\nvar _ = strings.ToUpper\n",
		textK8sAppYaml: "kind: Deployment\nmetadata:\n  name: api\n---\n" +
			"kind: Service\nmetadata:\n  name: api-svc\n",
		"assets/logo.png":    "\x89PNG\x00\x00binary",
		textNotesUntrackedMd: "TODO-2 untracked\n",
	}
}

// sourceOf returns a generated CodebaseSource mock serving viewFiles, counting each
// file's reads, with notes/untracked.md untracked.
func sourceOf(t *testing.T) (*mocks.MockCodebaseSource, map[string]int, *sync.Mutex) {
	t.Helper()

	src := mocks.NewMockCodebaseSource(gomock.NewController(t))
	files := viewFiles()
	list := make([]types.File, 0, len(files))

	for p := range files {
		list = append(list, types.File{Path: p, Untracked: p == textNotesUntrackedMd})
	}

	slices.SortFunc(
		list,
		func(a, b types.File) int { return cmp.Compare(a.Path, b.Path) },
	)
	src.EXPECT().List(gomock.Any()).Return(list, nil).AnyTimes()

	reads := map[string]int{}

	var lock sync.Mutex

	src.EXPECT().Read(gomock.Any(), gomock.Any()).DoAndReturn(
		func(_ context.Context, text string) ([]byte, error) {
			lock.Lock()

			reads[text]++
			lock.Unlock()

			body, ok := files[text]
			if !ok {
				return nil, apperr.NotFound(text)
			}

			return []byte(body), nil
		}).AnyTimes()

	return src, reads, &lock
}

// TestCodebase_FilesTextAndMatch tests the file, text and pattern views over a source.
//
// Why this test is important:
//   - Every check selects files and scans their text; the views must apply the
//     selector, skip generated and binary files, and read each file once however many
//     checks scan it.
//
// What it tests:
//   - Files applies the selector, drops the generated Go file by default and keeps it
//     on request, and TrackedOnly drops the untracked note; Match returns line and
//     column hits from text files only; repeated Text and Match calls read each file
//     once; Rendered without a renderer is CodeUnavailable.
func TestCodebase_FilesTextAndMatch(t *testing.T) {
	t.Parallel()

	testCodebaseFilesTextAndMatchRest5(t)
}

// testCodebaseFilesTextAndMatchRest5 continues testCodebaseFilesTextAndMatchRest4 with
// its
// remaining steps.
func testCodebaseFilesTextAndMatchRest5(t *testing.T) {
	t.Helper()

	src, reads, lock := sourceOf(t)
	codebaseValue := codebase.New(src, codebase.NewSnapshot(textT), nil)
	ctx := t.Context()

	files, err := codebaseValue.Files(ctx, &types.FileSelector{Exts: []string{textGo3}})
	require.NoError(t, err)
	assert.Equal(t, []string{textSvcAMainGo, textSvcBBGo}, paths(files))

	files, err = codebaseValue.Files(
		ctx,
		&types.FileSelector{Exts: []string{textGo3}, IncludeGenerated: true},
	)
	require.NoError(t, err)
	assert.Equal(
		t,
		[]string{textSvcAMainGo, "svc/a/main.pb.go", textSvcBBGo},
		paths(files),
	)

	files, err = codebaseValue.Files(
		ctx,
		&types.FileSelector{Roots: []string{"notes"}, TrackedOnly: true},
	)
	require.NoError(t, err)
	assert.Empty(t, files)

	testCodebaseFilesTextAndMatchRest(ctx, t, reads, lock, codebaseValue)
}

// testCodebaseFilesTextAndMatchRest continues testCodebaseFilesTextAndMatchRest5 with its
// remaining steps.
func testCodebaseFilesTextAndMatchRest(
	ctx context.Context,
	t *testing.T,
	reads map[string]int,
	lock *sync.Mutex,
	codebaseValue interfaces.Codebase,
) {
	t.Helper()

	var err error

	hits, err := codebaseValue.Match(
		ctx,
		&types.FileSelector{},
		[]*regexp.Regexp{regexp.MustCompile(`TODO-\d`)},
	)
	require.NoError(t, err)
	require.Len(t, hits, wantHitsLen2)
	assert.Equal(
		t,
		types.Hit{
			File:    textNotesUntrackedMd,
			Line:    1,
			Col:     1,
			Text:    "TODO-2 untracked",
			Pattern: `TODO-\d`,
		},
		hits[0],
	)
	assert.Equal(t, textSvcAMainGo, hits[1].File)
	assert.Equal(t, wantLine5, hits[1].Line)

	_, err = codebaseValue.Match(
		ctx,
		&types.FileSelector{},
		[]*regexp.Regexp{regexp.MustCompile(`PNG`)},
	)
	require.NoError(t, err)

	text, err := codebaseValue.Text(ctx, "assets/logo.png")
	require.NoError(t, err)
	assert.True(t, text.Binary)

	lock.Lock()

	for p, n := range reads {
		assert.Equal(t, 1, n, "%s read once", p)
	}

	lock.Unlock()

	_, err = codebaseValue.Rendered(ctx, &types.RenderSpec{ChartDir: textChartsAPI})
	assert.Equal(t, apperr.CodeUnavailable, apperr.Code(err))
}

// TestCodebase_GoAndYAMLViews tests the parsed Go and YAML views.
//
// Why this test is important:
//   - Go guards and YAML checks were each parsing the whole repository on their own;
//     the views must give them module lists, ASTs and decoded documents parsed once.
//
// What it tests:
//   - Modules reads go.work; Parse returns ASTs with their imports and skips the
//     generated file; parsing the same files twice returns the same ASTs; Docs lists both
//     documents; Query selects a field with its line; Decode fills a struct.
func TestCodebase_GoAndYAMLViews(t *testing.T) {
	t.Parallel()

	src, _, _ := sourceOf(t)
	codebaseValue := codebase.New(src, codebase.NewSnapshot(textT), nil)
	ctx := t.Context()

	mods, err := codebaseValue.Go().Modules(ctx)
	require.NoError(t, err)
	assert.Equal(t, []string{"svc/a", "svc/b"}, mods)

	sel := types.FileSelector{Roots: []string{textSvc}}
	gofiles, err := codebaseValue.Go().Parse(ctx, &sel, types.ParseImports)
	require.NoError(t, err)
	require.Len(t, gofiles, wantGofilesLen2)
	assert.Equal(t, textSvcBBGo, gofiles[1].Path)
	assert.Len(t, gofiles[1].AST.Imports, wantImportsLen2)

	again, err := codebaseValue.Go().Parse(ctx, &sel, types.ParseImports)
	require.NoError(t, err)
	assert.Same(t, gofiles[0].AST, again[0].AST)

	docs, err := codebaseValue.YAML().
		Docs(ctx, &types.FileSelector{Exts: []string{textYaml}})
	require.NoError(t, err)
	assert.Equal(
		t,
		[]types.YAMLDoc{
			{Path: textK8sAppYaml, Index: 0},
			{Path: textK8sAppYaml, Index: 1},
		},
		docs,
	)

	got, err := codebaseValue.YAML().Query(ctx, docs[1], "$.metadata.name")
	require.NoError(t, err)
	assert.Equal(t, []types.YAMLMatch{{Value: "api-svc", Kind: textScalar, Line: 7}}, got)

	var obj struct {
		Kind string `yaml:"kind"`
	}

	require.NoError(t, codebaseValue.YAML().Decode(ctx, docs[0], &obj))
	assert.Equal(t, textDeployment, obj.Kind)
}

// TestCodebase_RenderedIsMemoized tests that a render runs once per spec.
//
// Why this test is important:
//   - Chart renders cost seconds each; several checks assert on the same render.
//
// What it tests:
//   - Two Rendered calls for one spec call the renderer once and return its objects.
func TestCodebase_RenderedIsMemoized(t *testing.T) {
	t.Parallel()

	src, _, _ := sourceOf(t)
	renderer := mocks.NewMockRenderer(gomock.NewController(t))
	spec := types.RenderSpec{ChartDir: textChartsAPI, ValuesFiles: []string{"v.yaml"}}
	renderer.EXPECT().Render(gomock.Any(), any(&spec)).
		Return([]types.Object{{Kind: textDeployment, Name: textAPI}}, nil).Times(1)

	r := codebase.New(src, codebase.NewSnapshot(textT), renderer)
	for range iterations2 {
		objs, err := r.Rendered(t.Context(), &spec)
		require.NoError(t, err)
		assert.Equal(t, textAPI, objs[0].Name)
	}
}

// paths returns each file's path.
func paths(files []types.File) []string {
	out := make([]string, 0, len(files))
	for _, f := range files {
		out = append(out, f.Path)
	}

	return out
}

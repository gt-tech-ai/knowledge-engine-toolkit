// fsCodebase is a working-tree codebase over root.
func fsCodebase(t *testing.T, root string) interfaces.Codebase {
	t.Helper()
	cb, err := clientcodebase.NewFromConfig(t.Context(),
		clientcodebase.Config{Kind: clientcodebase.KindFS, Root: root}, clientcodebase.Deps{})
	require.NoError(t, err)
	return cb
}

// mockgenHeader is the header mockgen writes for argv, as `go generate` sees it.
func mockgenHeader(argv string) string {
	return "// Code generated by MockGen. DO NOT EDIT.\n//\n" +
		"// Generated by this command:\n" +
		"//\n//\tmockgen " + argv + "\n//\n\npackage gen\n"
}

// writeMockDir writes root/gen/generate.go holding directives and returns the dir.
func writeMockDir(t *testing.T, root string, directives ...string) string {
	t.Helper()
	dir := filepath.Join(root, "gen")
	require.NoError(t, os.MkdirAll(dir, 0o755))
	var b strings.Builder
	b.WriteString("package gen\n\n")
	for _, d := range directives {
		b.WriteString("//go:generate " + d + "\n")
	}
	src := b.String()
	require.NoError(
		t,
		os.WriteFile(filepath.Join(dir, "generate.go"), []byte(src), 0o600),
	)
	return dir
}

// TestMockgenGenerator_RendersDirectivesIntoMemory tests the mocks generator's render.
//
// Why this test is important:
//   - The mocks drift guard compares on-disk mocks with this render, so it must be
//     byte-equal to what `go generate` writes: the same argv in the same directory,
//     with the header line carrying the directive's own -destination.
//
// What it tests:
//   - Each directive runs mockgen without -destination in the directive's directory,
//     its stdout is keyed by the destination, and the argv header is rewritten to the
//     directive's argv; a -source directive and a nested destination both work.
func TestMockgenGenerator_RendersDirectivesIntoMemory(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	dir := writeMockDir(t, root,
		"mockgen -destination=mock_x.go -package=gen example.com/x X",
		"mockgen -source=iface.go -destination=sub/mock_iface.go -package=gen",
	)

	runner := mocks.NewMockCommandRunner(gomock.NewController(t))
	runner.EXPECT().RequireTool("mockgen", gomock.Any()).Return(nil)
	runner.EXPECT().
		RunBuffered(gomock.Any(), dir, "mockgen", "-package=gen", "example.com/x", "X").
		Return(interfaces.CmdResult{
			Stdout: []byte(mockgenHeader("-package=gen example.com/x X")),
		})
	runner.EXPECT().
		RunBuffered(gomock.Any(), dir, "mockgen", "-source=iface.go", "-package=gen").
		Return(interfaces.CmdResult{
			Stdout: []byte(mockgenHeader("-source=iface.go -package=gen")),
		})

	out, err := mockgen.NewGenerator([]string{"gen"}, runner, root).
		Render(t.Context(), fsCodebase(t, root))

	require.NoError(t, err)
	assert.Equal(t, types.Artifacts{
		"gen/mock_x.go": []byte(mockgenHeader(
			"-destination=mock_x.go -package=gen example.com/x X",
		)),
		"gen/sub/mock_iface.go": []byte(mockgenHeader(
			"-source=iface.go -destination=sub/mock_iface.go -package=gen",
		)),
	}, out)
}

// TestMockgenGenerator_RejectsForeignDirective tests that a directive the generator
// cannot render fails loudly.
//
// Why this test is important:
//   - A mock dir with a non-mockgen go:generate line, or a mockgen line with no
//     destination, would otherwise be silently skipped and its mock never checked.
//
// What it tests:
//   - A `go run` directive fails with CodeInvalidInput naming the file and line; a
//     mockgen directive without -destination fails the same way.
func TestMockgenGenerator_RejectsForeignDirective(t *testing.T) {
	t.Parallel()
	for _, tc := range []struct{ name, directive, want string }{
		{"foreign tool", "go run ./tool", "only mockgen"},
		{"no destination", "mockgen -package=gen example.com/x X", "-destination"},
	} {
		t.Run(tc.name, func(t *testing.T) {
			t.Parallel()
			root := t.TempDir()
			writeMockDir(t, root, tc.directive)
			runner := mocks.NewMockCommandRunner(gomock.NewController(t))
			runner.EXPECT().RequireTool("mockgen", gomock.Any()).Return(nil)

			_, err := mockgen.NewGenerator([]string{"gen"}, runner, root).
				Render(t.Context(), fsCodebase(t, root))

			require.Error(t, err)
			assert.True(t, apperr.Is(err, apperr.CodeInvalidInput), err)
			assert.Contains(t, err.Error(), "gen/generate.go:3")
			assert.Contains(t, err.Error(), tc.want)
		})
	}
}

// TestMockgenGenerator_FailsOnToolErrors tests the two tool failures.
//
// Why this test is important:
//   - A missing mockgen or a failing run must surface as the generator's error, never
//     as an empty render that the drift check would read as "every mock missing".
//
// What it tests:
//   - A missing tool returns RequireTool's error before any directive is read; a
//     failing mockgen run is CodeInternal naming the mock and mockgen's stderr.
func TestMockgenGenerator_FailsOnToolErrors(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	dir := writeMockDir(
		t,
		root,
		"mockgen -destination=mock_x.go -package=gen example.com/x X",
	)

	missing := mocks.NewMockCommandRunner(gomock.NewController(t))
	missing.EXPECT().RequireTool("mockgen", gomock.Any()).
		Return(apperr.NotFound("mockgen not found on PATH"))
	_, err := mockgen.NewGenerator([]string{"gen"}, missing, root).
		Render(t.Context(), fsCodebase(t, root))
	require.Error(t, err)
	assert.True(t, apperr.Is(err, apperr.CodeNotFound), err)

	failing := mocks.NewMockCommandRunner(gomock.NewController(t))
	failing.EXPECT().RequireTool("mockgen", gomock.Any()).Return(nil)
	failing.EXPECT().
		RunBuffered(gomock.Any(), dir, "mockgen", "-package=gen", "example.com/x", "X").
		Return(interfaces.CmdResult{
			Err:      assert.AnError,
			ExitCode: 1,
			Stderr:   []byte("cannot load example.com/x\n"),
		})
	_, err = mockgen.NewGenerator([]string{"gen"}, failing, root).
		Render(t.Context(), fsCodebase(t, root))
	require.Error(t, err)
	assert.True(t, apperr.Is(err, apperr.CodeInternal), err)
	assert.Contains(t, err.Error(), "gen/mock_x.go")
	assert.Contains(t, err.Error(), "cannot load example.com/x")
}

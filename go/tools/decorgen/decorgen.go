// Package decorgen generates decorators: for each named interface, a Decorated<Name> type
// whose every operation — a method taking a context.Context first and returning an error
// last — runs through a decorate.Subject (the Exec every tier's Base embeds), named by the
// method, and whose other methods pass straight through. It is the Go counterpart of
// Python's runtime decorate(client, base): a component's custom operations get its tier's
// layers without a hand-written wrapper per method. The cmd/decorgen binary runs it from a
// go:generate directive.
package decorgen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	pathpkg "path"
	"slices"
	"strings"

	"golang.org/x/tools/go/packages"

	apperr "github.com/gt-tech-ai/knowledge-engine-toolkit/go/core/errors"
)

// decoratePath is the import path of the package the generated code runs through.
const decoratePath = "github.com/gt-tech-ai/knowledge-engine-toolkit/go/foundation/decorate"

// Config selects the interfaces to decorate and where the generated code lives.
type Config struct {
	// Source is the package pattern holding the interfaces ("." or an import path),
	// resolved from Dir.
	Source string

	// Dir is the directory patterns resolve from; empty is the working directory.
	Dir string

	// Package is the generated file's package name.
	Package string

	// PackagePath is the generated file's import path, so the types it declares are
	// written unqualified; empty qualifies every named type.
	PackagePath string

	// Interfaces names the interfaces to decorate, in output order.
	Interfaces []string
}

// Generate returns the gofmt'd source declaring a Decorated<Name> for each interface in
// cfg. An unknown, generic or non-interface name is CodeInvalidInput; a package that
// fails to load is CodeInternal.
func Generate(cfg Config) ([]byte, error) {
	if cfg.Package == "" || len(cfg.Interfaces) == 0 {
		return nil, apperr.New(apperr.CodeInvalidInput,
			"decorgen: a package name and at least one interface are required")
	}
	pkg, err := load(cfg)
	if err != nil {
		return nil, err
	}
	g := newGenerator(cfg.PackagePath)
	var body bytes.Buffer
	for _, name := range cfg.Interfaces {
		named, iface, err := lookup(pkg, name)
		if err != nil {
			return nil, err
		}
		g.decorator(&body, named, iface)
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by decorgen; DO NOT EDIT.\n\npackage %s\n\n", cfg.Package)
	g.imports(&out)
	out.Write(body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return nil, apperr.Wrap(err, apperr.CodeInternal, "decorgen: format the generated source")
	}
	return src, nil
}

// load type-checks the package cfg.Source names.
func load(cfg Config) (*types.Package, error) {
	pkgs, err := packages.Load(&packages.Config{
		Mode: packages.NeedName | packages.NeedTypes | packages.NeedImports |
			packages.NeedDeps,
		Dir: cfg.Dir,
	}, cfg.Source)
	if err != nil {
		return nil, apperr.Wrap(err, apperr.CodeInternal, "decorgen: load "+cfg.Source)
	}
	if len(pkgs) != 1 {
		return nil, apperr.New(apperr.CodeInvalidInput, fmt.Sprintf(
			"decorgen: %q matches %d packages, want 1", cfg.Source, len(pkgs)))
	}
	if errs := pkgs[0].Errors; len(errs) > 0 {
		return nil, apperr.New(apperr.CodeInternal, fmt.Sprintf(
			"decorgen: load %s: %v", cfg.Source, errs[0]))
	}
	return pkgs[0].Types, nil
}

// lookup returns the non-generic interface named name in pkg.
func lookup(pkg *types.Package, name string) (*types.Named, *types.Interface, error) {
	obj, ok := pkg.Scope().Lookup(name).(*types.TypeName)
	if !ok {
		return nil, nil, apperr.New(apperr.CodeInvalidInput, fmt.Sprintf(
			"decorgen: no type %s in %s", name, pkg.Path()))
	}
	named, ok := obj.Type().(*types.Named)
	if !ok || named.TypeParams().Len() > 0 {
		return nil, nil, apperr.New(apperr.CodeInvalidInput, fmt.Sprintf(
			"decorgen: %s.%s is not a non-generic named type", pkg.Path(), name))
	}
	iface, ok := named.Underlying().(*types.Interface)
	if !ok {
		return nil, nil, apperr.New(apperr.CodeInvalidInput, fmt.Sprintf(
			"decorgen: %s.%s is not an interface", pkg.Path(), name))
	}
	return named, iface, nil
}

// generator writes decorators, tracking the imports their types need.
type generator struct {
	// aliases maps an imported package path to the name the file refers to it by.
	aliases map[string]string

	// names maps an imported package path to its package name.
	names map[string]string

	// self is the generated file's import path; its types are written unqualified.
	self string
}

// newGenerator returns a generator for a file whose import path is self.
func newGenerator(self string) *generator {
	return &generator{self: self, aliases: map[string]string{}, names: map[string]string{}}
}

// qualify is the types.Qualifier that names pkg by its import alias.
func (g *generator) qualify(pkg *types.Package) string {
	if pkg.Path() == g.self {
		return ""
	}
	return g.alias(pkg.Path(), pkg.Name())
}

// alias returns the name path is imported as, choosing name, or name with a numeric
// suffix when another path already took it.
func (g *generator) alias(path, name string) string {
	if a, ok := g.aliases[path]; ok {
		return a
	}
	a := name
	for i := 2; slices.Contains(g.taken(), a); i++ {
		a = fmt.Sprintf("%s%d", name, i)
	}
	g.aliases[path] = a
	g.names[path] = name
	return a
}

// taken lists the aliases in use.
func (g *generator) taken() []string {
	out := make([]string, 0, len(g.aliases))
	for _, a := range g.aliases {
		out = append(out, a)
	}
	return out
}

// imports writes the import block.
func (g *generator) imports(out *bytes.Buffer) {
	paths := make([]string, 0, len(g.aliases))
	for p := range g.aliases {
		paths = append(paths, p)
	}
	slices.Sort(paths)
	out.WriteString("import (\n")
	for _, p := range paths {
		if a := g.aliases[p]; a != g.names[p] || a != pathpkg.Base(p) {
			fmt.Fprintf(out, "\t%s %q\n", a, p)
			continue
		}
		fmt.Fprintf(out, "\t%q\n", p)
	}
	out.WriteString(")\n\n")
}

// typ writes t qualified by the file's imports.
func (g *generator) typ(t types.Type) string { return types.TypeString(t, g.qualify) }

// decorator writes the Decorated<Name> type for the interface named over iface.
func (g *generator) decorator(out *bytes.Buffer, named *types.Named, iface *types.Interface) {
	name := named.Obj().Name()
	dec := "Decorated" + name
	ifaceType := g.typ(named)
	subject := g.alias(decoratePath, "decorate") + ".Subject"
	fmt.Fprintf(out, `// %[1]s runs every operation of the %[2]s it wraps through its subject's
// decoration, as the operation named by the method.
type %[1]s struct {
	// next is the wrapped %[2]s.
	next %[3]s

	// subject runs each operation through the tier's layers.
	subject %[4]s
}

var _ %[3]s = (*%[1]s)(nil)

// New%[1]s returns next decorated by subject.
func New%[1]s(next %[3]s, subject %[4]s) *%[1]s {
	return &%[1]s{next: next, subject: subject}
}

`, dec, name, ifaceType, subject)
	for i := range iface.NumMethods() {
		g.method(out, dec, iface.Method(i))
	}
}

// method writes one method of the decorator named dec.
func (g *generator) method(out *bytes.Buffer, dec string, m *types.Func) {
	sig := m.Type().(*types.Signature)
	params, args := g.params(sig)
	results := g.results(sig)
	op := decorated(sig)
	if vals := sig.Results().Len() - 1; op && vals > 1 {
		g.tupleType(out, dec, m.Name(), sig, vals)
	}
	if op {
		fmt.Fprintf(out, "// %s runs the wrapped %s as the operation %q.\n",
			m.Name(), m.Name(), m.Name())
	} else {
		fmt.Fprintf(out, "// %s calls the wrapped %s undecorated: it is not an operation.\n",
			m.Name(), m.Name())
	}
	fmt.Fprintf(out, "func (d *%s) %s(%s) %s {\n", dec, m.Name(), params, results)
	call := fmt.Sprintf("d.next.%s(%s)", m.Name(), args)
	if !op {
		if sig.Results().Len() == 0 {
			fmt.Fprintf(out, "\t%s\n}\n\n", call)
		} else {
			fmt.Fprintf(out, "\treturn %s\n}\n\n", call)
		}
		return
	}
	ctxType := g.typ(sig.Params().At(0).Type())
	vals := sig.Results().Len() - 1
	switch vals {
	case 0:
		fmt.Fprintf(out, "\t_, err := d.subject.Exec(ctx, %q, func(ctx %s) (struct{}, error) {\n"+
			"\t\treturn struct{}{}, %s\n\t})\n\treturn err\n}\n\n", m.Name(), ctxType, call)
	case 1:
		fmt.Fprintf(out, "\treturn d.subject.Exec(ctx, %q, func(ctx %s) (%s, error) {\n"+
			"\t\treturn %s\n\t})\n}\n\n",
			m.Name(), ctxType, g.typ(sig.Results().At(0).Type()), call)
	default:
		g.tuple(out, tupleName(dec, m.Name()), m.Name(), ctxType, call, vals)
	}
}

// tupleName names the struct the values of the operation op of dec ride in.
func tupleName(dec, op string) string {
	return strings.ToLower(dec[:1]) + dec[1:] + op + "Result"
}

// tupleType declares the struct the values of an operation returning more than one value
// ride through the subject in, ahead of its method.
func (g *generator) tupleType(
	out *bytes.Buffer,
	dec, op string,
	sig *types.Signature,
	vals int,
) {
	name := tupleName(dec, op)
	fmt.Fprintf(out, "// %s carries the values %s.%s returns through the subject.\n"+
		"type %s struct {\n", name, dec, op, name)
	for i := range vals {
		fmt.Fprintf(out, "\tr%d %s\n", i, g.typ(sig.Results().At(i).Type()))
	}
	out.WriteString("}\n\n")
}

// tuple writes the body of an operation returning more than one value: the values ride
// through the subject in the struct named tuple.
func (g *generator) tuple(out *bytes.Buffer, tuple, op, ctxType, call string, vals int) {
	names := make([]string, vals)
	got := make([]string, vals)
	for i := range vals {
		names[i] = fmt.Sprintf("r%d", i)
		got[i] = "res." + names[i]
	}
	list := strings.Join(names, ", ")
	fmt.Fprintf(out, "\tres, err := d.subject.Exec(ctx, %q, func(ctx %s) (%s, error) {\n"+
		"\t\t%s, err := %s\n\t\treturn %s{%s}, err\n\t})\n\treturn %s, err\n}\n\n",
		op, ctxType, tuple, list, call, tuple, list, strings.Join(got, ", "))
}

// decorated reports whether sig is an operation: a context.Context first and an error
// last.
func decorated(sig *types.Signature) bool {
	p, r := sig.Params(), sig.Results()
	if p.Len() == 0 || r.Len() == 0 {
		return false
	}
	return isNamed(p.At(0).Type(), "context", "Context") &&
		isNamed(r.At(r.Len()-1).Type(), "", "error")
}

// isNamed reports whether t is the named type pkg.name ("" for a universe type).
func isNamed(t types.Type, pkg, name string) bool {
	n, ok := t.(*types.Named)
	if !ok || n.Obj().Name() != name {
		return false
	}
	if n.Obj().Pkg() == nil {
		return pkg == ""
	}
	return n.Obj().Pkg().Path() == pkg
}

// params returns sig's parameter list (the first named ctx when it is a context, the
// rest by the interface's names, or p<i>) and the argument list that forwards them.
func (g *generator) params(sig *types.Signature) (string, string) {
	n := sig.Params().Len()
	typs := make([]string, n)
	for i := range n {
		t := sig.Params().At(i).Type()
		if sig.Variadic() && i == n-1 {
			typs[i] = "..." + g.typ(t.(*types.Slice).Elem())
			continue
		}
		typs[i] = g.typ(t)
	}
	decls := make([]string, n)
	args := make([]string, n)
	for i := range n {
		v := sig.Params().At(i)
		name := g.paramName(v.Name(), i)
		if i == 0 && isNamed(v.Type(), "context", "Context") {
			name = "ctx"
		}
		decls[i] = name + " " + typs[i]
		args[i] = name
		if sig.Variadic() && i == n-1 {
			args[i] += "..."
		}
	}
	return strings.Join(decls, ", "), strings.Join(args, ", ")
}

// paramName is the interface's own name for the parameter at i, or p<i> when it has none
// or the name would shadow a name the generated method uses: the receiver, the body's
// locals, or an imported package.
func (g *generator) paramName(name string, i int) string {
	switch {
	case name == "", name == "_", name == "ctx", name == "d", name == "res", name == "err",
		len(name) > 1 && name[0] == 'r' && strings.Trim(name[1:], "0123456789") == "",
		slices.Contains(g.taken(), name):
		return fmt.Sprintf("p%d", i)
	default:
		return name
	}
}

// results returns sig's result list.
func (g *generator) results(sig *types.Signature) string {
	r := sig.Results()
	switch r.Len() {
	case 0:
		return ""
	case 1:
		return g.typ(r.At(0).Type())
	}
	out := make([]string, r.Len())
	for i := range r.Len() {
		out[i] = g.typ(r.At(i).Type())
	}
	return "(" + strings.Join(out, ", ") + ")"
}

// Package opmockgen generates the mocks of operation contracts: for each named struct
// whose fields are interfaces (an interfaces.Op per operation, engine role interfaces,
// and the app's own interfaces) or embedded structs of them, a Mock<Name> holding one
// gomock mock per interface field, flattened through the embedded structs, and a
// Contract method that assembles the struct from them. mockgen covers interfaces; this
// covers the structs of operations an app's contracts are made of. The cmd/opmockgen
// binary runs it from a go:generate directive.
package opmockgen

import (
	"bytes"
	"fmt"
	"go/format"
	"go/types"
	"strings"

	"golang.org/x/tools/go/packages"

	apperr "github.com/gt-tech-ai/knowledge-engine-toolkit/go/core/errors"
	"github.com/gt-tech-ai/knowledge-engine-toolkit/go/tools/internal/gofile"
)

const (
	// coreInterfacesPath is the engine's core-interfaces package; an interface declared
	// there is mocked by the engine's published mocks.
	coreInterfacesPath = "github.com/gt-tech-ai/knowledge-engine-toolkit/go/core/interfaces"

	// engineMocksPath is the engine's published mocks package.
	engineMocksPath = "github.com/gt-tech-ai/knowledge-engine-toolkit/go/tests/mocks"

	// gomockPath is the gomock package the generated constructors take a controller from.
	gomockPath = "go.uber.org/mock/gomock"
)

// Config selects the contracts to mock and where the generated code lives.
type Config struct {
	// Source is the package pattern holding the contracts ("." or an import path),
	// resolved from Dir.
	Source string

	// Dir is the directory patterns resolve from; empty is the working directory.
	Dir string

	// Package is the generated file's package name.
	Package string

	// PackagePath is the generated file's import path. An interface declared outside the
	// engine's core-interfaces package is mocked by the mockgen mock of the same name in
	// this package (MockName, NewMockName), so it must be generated alongside.
	PackagePath string

	// Structs names the contracts to mock, in output order.
	Structs []string
}

// Generate returns the gofmt'd source declaring a Mock<Name> for each contract in cfg.
// An unknown name, a generic or non-struct type, a field that is neither an interface
// nor an embedded struct, and two fields promoted to the same name are
// CodeInvalidInput; a package that fails to load is CodeInternal.
func Generate(cfg Config) ([]byte, error) {
	if cfg.Package == "" || len(cfg.Structs) == 0 {
		return nil, apperr.New(apperr.CodeInvalidInput,
			"opmockgen: a package name and at least one struct are required")
	}
	pkg, err := load(cfg)
	if err != nil {
		return nil, err
	}
	g := &generator{Imports: gofile.NewImports(cfg.PackagePath)}
	var body bytes.Buffer
	for _, name := range cfg.Structs {
		named, err := lookup(pkg, name)
		if err != nil {
			return nil, err
		}
		if err := g.mock(&body, named); err != nil {
			return nil, err
		}
	}
	var out bytes.Buffer
	fmt.Fprintf(&out, "// Code generated by opmockgen; DO NOT EDIT.\n\npackage %s\n\n", cfg.Package)
	g.Write(&out)
	out.Write(body.Bytes())
	src, err := format.Source(out.Bytes())
	if err != nil {
		return nil, apperr.Wrap(err, apperr.CodeInternal, "opmockgen: format the generated source")
	}
	return src, nil
}

// load type-checks the package cfg.Source names.
func load(cfg Config) (*types.Package, error) {
	pkgs, err := packages.Load(&packages.Config{
		Mode: packages.NeedName | packages.NeedTypes | packages.NeedImports |
			packages.NeedDeps,
		Dir: cfg.Dir,
	}, cfg.Source)
	if err != nil {
		return nil, apperr.Wrap(err, apperr.CodeInternal, "opmockgen: load "+cfg.Source)
	}
	if len(pkgs) != 1 {
		return nil, apperr.New(apperr.CodeInvalidInput, fmt.Sprintf(
			"opmockgen: %q matches %d packages, want 1", cfg.Source, len(pkgs)))
	}
	if errs := pkgs[0].Errors; len(errs) > 0 {
		return nil, apperr.New(apperr.CodeInternal, fmt.Sprintf(
			"opmockgen: load %s: %v", cfg.Source, errs[0]))
	}
	return pkgs[0].Types, nil
}

// lookup returns the non-generic struct named name in pkg.
func lookup(pkg *types.Package, name string) (*types.Named, error) {
	obj, ok := pkg.Scope().Lookup(name).(*types.TypeName)
	if !ok {
		return nil, apperr.New(apperr.CodeInvalidInput, fmt.Sprintf(
			"opmockgen: no type %s in %s", name, pkg.Path()))
	}
	named, ok := types.Unalias(obj.Type()).(*types.Named)
	if !ok || named.TypeParams().Len() > 0 {
		return nil, apperr.New(apperr.CodeInvalidInput, fmt.Sprintf(
			"opmockgen: %s.%s is not a non-generic named type", pkg.Path(), name))
	}
	if _, ok := named.Underlying().(*types.Struct); !ok {
		return nil, apperr.New(apperr.CodeInvalidInput, fmt.Sprintf(
			"opmockgen: %s.%s is not a struct", pkg.Path(), name))
	}
	return named, nil
}

// generator writes mocks, tracking the imports their types need.
type generator struct {
	*gofile.Imports
}

// leaf is one interface field of a contract, flattened: the mock field that backs it.
type leaf struct {
	// name is the field's (promoted) name, the mock's field name.
	name string

	// mock is the mock's type, without the pointer.
	mock string

	// ctor is the expression that builds the mock from ctrl.
	ctor string
}

// mock writes the Mock<Name> of the contract named over its struct.
func (g *generator) mock(out *bytes.Buffer, named *types.Named) error {
	var leaves []leaf
	literal, err := g.literal(named, &leaves, map[string]bool{})
	if err != nil {
		return err
	}
	name := named.Obj().Name()
	ctrl := g.Alias(gomockPath, "gomock") + ".Controller"
	fmt.Fprintf(out, "// Mock%[1]s is the mock set behind the %[1]s contract: one gomock mock per\n"+
		"// operation and role. Contract assembles the %[1]s the code under test is given.\n"+
		"type Mock%[1]s struct {\n", name)
	for i, l := range leaves {
		if i > 0 {
			out.WriteString("\n")
		}
		fmt.Fprintf(out, "\t// %s mocks the contract's %s.\n\t%s *%s\n", l.name, l.name, l.name, l.mock)
	}
	fmt.Fprintf(out, "}\n\n// NewMock%[1]s returns a Mock%[1]s whose every mock is recorded by ctrl.\n"+
		"func NewMock%[1]s(ctrl *%[2]s) *Mock%[1]s {\n\treturn &Mock%[1]s{\n", name, ctrl)
	for _, l := range leaves {
		fmt.Fprintf(out, "\t\t%s: %s,\n", l.name, l.ctor)
	}
	fmt.Fprintf(out, "\t}\n}\n\n// Contract returns the %[1]s whose fields are m's mocks.\n"+
		"func (m *Mock%[1]s) Contract() %[2]s {\n\treturn %[3]s\n}\n\n",
		name, g.Type(named), literal)
	return nil
}

// literal returns the composite literal that builds the struct named from the mock's
// fields, appending a leaf per interface field (through embedded structs) to leaves.
// seen holds the promoted names already taken.
func (g *generator) literal(
	named *types.Named,
	leaves *[]leaf,
	seen map[string]bool,
) (string, error) {
	st, ok := named.Underlying().(*types.Struct)
	if !ok {
		return "", apperr.New(apperr.CodeInvalidInput, fmt.Sprintf(
			"opmockgen: %s is not a struct", named))
	}
	parts := make([]string, 0, st.NumFields())
	for i := range st.NumFields() {
		f := st.Field(i)
		ft := types.Unalias(f.Type())
		if f.Embedded() {
			if inner, ok := ft.(*types.Named); ok {
				if _, isStruct := inner.Underlying().(*types.Struct); isStruct {
					lit, err := g.literal(inner, leaves, seen)
					if err != nil {
						return "", err
					}
					parts = append(parts, fmt.Sprintf("%s: %s", f.Name(), lit))
					continue
				}
			}
		}
		l, err := g.leaf(named, f.Name(), ft)
		if err != nil {
			return "", err
		}
		if seen[l.name] {
			return "", apperr.New(apperr.CodeInvalidInput, fmt.Sprintf(
				"opmockgen: %s: two fields are promoted to %s", named, l.name))
		}
		seen[l.name] = true
		*leaves = append(*leaves, l)
		parts = append(parts, fmt.Sprintf("%s: m.%s", f.Name(), l.name))
	}
	return g.Type(named) + "{\n" + strings.Join(parts, ",\n") + ",\n}", nil
}

// leaf returns the mock backing the field named field, of type t, of the struct owner:
// the engine's published mock for an engine core interface, else the mockgen mock of the
// same name in the generated file's package.
func (g *generator) leaf(owner *types.Named, field string, t types.Type) (leaf, error) {
	iface, ok := t.(*types.Named)
	if !ok || !types.IsInterface(iface) {
		return leaf{}, apperr.New(apperr.CodeInvalidInput, fmt.Sprintf(
			"opmockgen: %s.%s is %s, not an interface or an embedded struct",
			owner, field, t))
	}
	// Any other interface's mockgen mock lives in the generated file's package, so it is
	// written unqualified.
	pkg := ""
	if obj := iface.Obj().Pkg(); obj != nil && obj.Path() == coreInterfacesPath {
		pkg = g.Alias(engineMocksPath, "mocks") + "."
	}
	args := ""
	if ta := iface.TypeArgs(); ta.Len() > 0 {
		list := make([]string, ta.Len())
		for i := range ta.Len() {
			list[i] = g.Type(ta.At(i))
		}
		args = "[" + strings.Join(list, ", ") + "]"
	}
	mockName := "Mock" + iface.Obj().Name()
	return leaf{
		name: field,
		mock: pkg + mockName + args,
		ctor: pkg + "New" + mockName + args + "(ctrl)",
	}, nil
}

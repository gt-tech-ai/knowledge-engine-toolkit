class ErrorCode(StrEnum):
    """Error codes shared between Go and Python services."""

    UNKNOWN = "UNKNOWN"
    """The fallback for an error that is not an AppError or carries no code.

    HTTP 500, gRPC INTERNAL; neither transient nor permanent.
    """

    INTERNAL = "INTERNAL"
    """An unexpected server-side failure.

    HTTP 500, gRPC INTERNAL; neither transient nor permanent.
    """

    NOT_FOUND = "NOT_FOUND"
    """A missing resource.

    HTTP 404, gRPC NOT_FOUND; permanent.
    """

    UNAUTHORIZED = "UNAUTHORIZED"
    """A missing or invalid authentication credential.

    HTTP 401, gRPC UNAUTHENTICATED; permanent.
    """

    FORBIDDEN = "FORBIDDEN"
    """An authenticated caller lacking permission for the action.

    HTTP 403, gRPC PERMISSION_DENIED; permanent.
    """

    INVALID_INPUT = "INVALID_INPUT"
    """A malformed or otherwise rejected request payload.

    HTTP 400, gRPC INVALID_ARGUMENT; permanent.
    """

    CONFLICT = "CONFLICT"
    """A state conflict, such as a duplicate or a concurrent modification.

    HTTP 409, gRPC ALREADY_EXISTS; permanent.
    """

    TIMEOUT = "TIMEOUT"
    """An operation that exceeded its deadline.

    HTTP 504, gRPC DEADLINE_EXCEEDED; transient.
    """

    CANCELED = "CANCELED"
    """An operation the caller canceled.

    HTTP 500, gRPC CANCELLED; neither transient nor permanent.
    """

    UNAVAILABLE = "UNAVAILABLE"
    """A temporarily unreachable dependency.

    HTTP 503, gRPC UNAVAILABLE; transient.
    """

    INGESTION_ERROR = "INGESTION_ERROR"
    """A failure in the document ingestion pipeline.

    HTTP 500, gRPC INTERNAL; neither transient nor permanent.
    """

    QUALITY_FAILED = "QUALITY_FAILED"
    """A failed quality gate.

    HTTP 500, gRPC INTERNAL; neither transient nor permanent.
    """

    UPSTREAM = "UPSTREAM"
    """A failure originating in an upstream dependency.

    HTTP 502, gRPC UNAVAILABLE; neither transient nor permanent.
    """

    RESOURCE_EXHAUSTED = "RESOURCE_EXHAUSTED"
    """A request rejected because a quota or budget is spent.

    HTTP 429, gRPC RESOURCE_EXHAUSTED; neither transient nor permanent.

    It is neither transient (retrying before the window resets only burns the quota check)
    nor permanent (the request succeeds once the window resets).
    """



TIER_STANDALONE: Final = "standalone"
"""The tier label of a primitive used outside a decorate tier."""


class Reason(StrEnum):
    """Why a call was refused before it ran."""

    BREAKER_OPEN = "breaker_open"
    """The circuit breaker was open or its half-open trial calls were taken."""
    BULKHEAD_FULL = "bulkhead_full"
    """The bulkhead had no free slot and sheds rather than queues."""
    RATE_LIMITED = "rate_limited"
    """The rate limiter had no token."""
    THROTTLED = "throttled"
    """The adaptive throttler shed the call locally."""
    BUDGET_EXHAUSTED = "budget_exhausted"
    """The request's retry budget refused another attempt."""


class BreakerState(StrEnum):
    """A circuit breaker's state."""

    CLOSED = "closed"
    """Calls pass and failures are counted."""
    HALF_OPEN = "half_open"
    """Trial calls probe whether the dependency recovered."""
    OPEN = "open"
    """Calls fail fast without running."""

    @property
    def gauge(self) -> float:
        """The number a gauge reports for this value."""
        gauges: dict[BreakerState, float] = {
            BreakerState.CLOSED: 0,
            BreakerState.HALF_OPEN: 1,
            BreakerState.OPEN: 2,
        }
        return gauges[self]


class HedgeOutcome(StrEnum):
    """What happened to a hedge's backup attempt."""

    FIRED = "fired"
    """The first attempt outlived the delay, so the backup was sent."""
    WON = "won"
    """The backup attempt finished first and its result was returned."""


class DeadLetterOutcome(StrEnum):
    """Whether a dead letter reached its backend."""

    SENT = "sent"
    """The backend stored the letter."""
    FAILED = "failed"
    """The backend refused the letter, which was logged and dropped."""


